import katex from '../assets/katex/0.18.11/katex.min.js';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
assert.equal(katex.version, '0.18.11');
const formulas = [String.raw`eGFR=142\times\min(Scr/\kappa,1)^{\alpha}\times\max(Scr/\kappa,1)^{-1.200}`, String.raw`\frac{U_{Na}\times P_{Cr}}{P_{Na}\times U_{Cr}}\times100`, String.raw`\Delta GFR=\frac{GFR_2-GFR_1}{t_2-t_1}`, String.raw`HCO_3^-=0.03\times pCO_2\times10^{pH-6.1}`, String.raw`\sqrt{\frac{height\times weight}{3600}}`, String.raw`\mathrm{Kt/V}=-\ln(R-0.008t)+(4-3.5R)\frac{UF}{W}`];
for (const formula of formulas) assert.match(katex.renderToString(formula, { trust: false, throwOnError: true }), /katex-mathml/);
const inheritedTrust = Object.create({ trust: true });
inheritedTrust.throwOnError = false;
assert.doesNotMatch(katex.renderToString(String.raw`\href{https://example.invalid}{test}`, inheritedTrust), /<a\b/);
const css = fs.readFileSync(path.join(root, 'assets/katex/0.18.11/katex.min.css'), 'utf8');
for (const match of css.matchAll(/url\(([^)]+)\)/g)) assert.ok(fs.existsSync(path.join(root, 'assets/katex/0.18.11', match[1])));
const options = fs.readFileSync(path.join(root, 'formula-math.js'), 'utf8');
assert.match(options, /trust:\s*false/);
assert.match(options, /maxExpand:\s*1000/);
assert.match(options, /maxSize:\s*50/);
console.log('KaTeX: version, six formula families, inherited trust, font references and resource limits PASS');
